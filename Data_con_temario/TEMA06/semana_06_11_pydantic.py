class AppConfigEnv(BaseSettings):
    model_config = SettingsConfigDict(
        env_file=".env",
        env_file_encoding="utf-8",
        case_sensitive=True,
        extra="forbid",
    )

    base_de_datos_host: HttpUrl
    base_de_datos_usuario: str = Field(min_length=5)
    base_de_datos_password: str = Field(min_length=10)
    api_key: str = Field(min_length=20)

