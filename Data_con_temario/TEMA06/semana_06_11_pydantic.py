from uuid import UUID, uuid4
from enum import Enum
from pydantic import BaseModel, EmailStr, ValidationError


class Departamento(Enum):
    RRHH = "RRHH"
    VENTAS = "VENTAS"
    TI = "TI"
    INGENIERIA = "INGENIERIA"

