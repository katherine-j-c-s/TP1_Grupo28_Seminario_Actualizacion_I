from abc import ABC, abstractmethod

class Figura(ABC):
    """ Clase abstracta Figura.
    """

    @abstractmethod
    def calcular_area(self) -> float:
        """ Calcula el área

        Returns:
            float: Returna el área.
        """
        pass

"""## Ejercicio 8
Crear una clase Cuadrado que herede de Figura e implemente el método calcular_area para calcular el área de un cuadrado.
"""



#@title Solución

class Cuadrado(Figura):
    """ Clase Cuadrado.
    """

    def __init__(self, lado:float):
        """ Constructor

        Args:
          lado (float): Medida del lado.
        """
        self.lado:float = lado

    def calcular_area(self) -> float:
        """ Calcula el área

        Returns:
            float: Returna el área.
        """
        return self.lado ** 2

cuadrado = Cuadrado(lado=3)
print(f'El área de un cuadado de lado igual a {cuadrado.lado} es : {cuadrado.calcular_area()}')

"""## Ejercicio 9
Crear una clase Triangulo que herede de Figura e implemente el método calcular_area para calcular el área de un triángulo.
"""



#@title Solución

class Triangulo(Figura):
    def __init__(self, base:float, altura:float):
        """ Constructor

        Args:
          base (float): Medida de la base.
          altura (float): Medida de la altura.
        """
        self.base:float = base
        self.altura:float = altura

    def calcular_area(self) -> float:
        """ Calcula el área

        Returns:
            float: Returna el área.
        """
        return (self.base * self.altura) / 2


triangulo = Triangulo(base=3, altura=8)
print(f'El área de un triánguloa de base igual a {triangulo.base} y de altura igual a {triangulo.altura} es : {triangulo.calcular_area()}')

