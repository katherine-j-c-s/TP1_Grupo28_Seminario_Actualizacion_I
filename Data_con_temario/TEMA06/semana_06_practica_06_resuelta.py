def calcular_area_total(figuras:list[Figura]) -> float:
    """ Cacula el área total de las figuras

    Args:
        figuras (list[Figuras]): Lista de figuras.

    Returns:
        float: Retorna la suma de las áreas de cada figura.
    """
    return sum(map(lambda f: f.calcular_area(), figuras))

