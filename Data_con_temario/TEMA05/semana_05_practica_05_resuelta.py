def e7_intrigande(c:int):
  """ Función que prueba la hipótesiss.

  Args:
    c (int): Contiene el valor de c.

  """

  if c > 1:
    paso = 0
    while c != 1:
      if c % 2 != 0:
        c = 3 * c + 1
      else:
        c = c // 2
      print(f'Paso {paso:04d}: {c}')
      paso += 1

    print(f'Paso {paso:010d}: {c}')

    print(f'Se necesitaron {paso} pasos.')
  else:
    print('Valor de c es incorrecto')

