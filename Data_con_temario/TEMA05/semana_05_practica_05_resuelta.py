def e5_quitar_vocales(frase:str) -> str:
  """ Función que elimina vocales.

  Args:
    frase (str): Contiene la frase.

  Returns:
    str: Retorna la nueva frase sin vocales.
  """
  respuesta:str = ''
  vocales:list[str] = ['a', 'e', 'i', 'o', 'u', 'á', 'é', 'í', 'í', 'ú']
  for caracter in frase:
    if caracter.lower() not in vocales:
      respuesta += caracter
  return respuesta

